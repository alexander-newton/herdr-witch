#!/usr/bin/env python3
"""Generate src/render/octant_table.rs from Unicode 16+ UnicodeData.txt.

Usage: python3 -I scripts/gen_octants.py <path-to-UnicodeData.txt> > src/render/octant_table.rs

Bit i of a table index is sub-cell i+1 of the 2x4 grid (cells 1 2 / 3 4 / 5 6 / 7 8).
"""
import re
import sys

# Characters the octant block deliberately omits, as cell lists, found by name.
OMITTED = {
    "SPACE": [],
    "FULL BLOCK": [1, 2, 3, 4, 5, 6, 7, 8],
    "UPPER HALF BLOCK": [1, 2, 3, 4],
    "LOWER HALF BLOCK": [5, 6, 7, 8],
    "LEFT HALF BLOCK": [1, 3, 5, 7],
    "RIGHT HALF BLOCK": [2, 4, 6, 8],
    "QUADRANT LOWER LEFT": [5, 7],
    "QUADRANT LOWER RIGHT": [6, 8],
    "QUADRANT UPPER LEFT": [1, 3],
    "QUADRANT UPPER RIGHT": [2, 4],
    "QUADRANT UPPER LEFT AND LOWER RIGHT": [1, 3, 6, 8],
    "QUADRANT UPPER RIGHT AND LOWER LEFT": [2, 4, 5, 7],
    "QUADRANT UPPER LEFT AND UPPER RIGHT AND LOWER LEFT": [1, 2, 3, 4, 5, 7],
    "QUADRANT UPPER LEFT AND UPPER RIGHT AND LOWER RIGHT": [1, 2, 3, 4, 6, 8],
    "QUADRANT UPPER LEFT AND LOWER LEFT AND LOWER RIGHT": [1, 3, 5, 6, 7, 8],
    "QUADRANT UPPER RIGHT AND LOWER LEFT AND LOWER RIGHT": [2, 4, 5, 6, 7, 8],
    "LOWER ONE QUARTER BLOCK": [7, 8],
    "LOWER THREE QUARTERS BLOCK": [3, 4, 5, 6, 7, 8],
    "UPPER ONE QUARTER BLOCK": [1, 2],
    "UPPER THREE QUARTERS BLOCK": [1, 2, 3, 4, 5, 6],
    "MIDDLE LEFT ONE QUARTER BLOCK": [3, 5],
    "MIDDLE RIGHT ONE QUARTER BLOCK": [4, 6],
    "LEFT HALF UPPER ONE QUARTER BLOCK": [1],
    "RIGHT HALF UPPER ONE QUARTER BLOCK": [2],
    "LEFT HALF LOWER ONE QUARTER BLOCK": [7],
    "RIGHT HALF LOWER ONE QUARTER BLOCK": [8],
}


def bits(cells):
    b = 0
    for c in cells:
        b |= 1 << (c - 1)
    return b


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_octants.py <UnicodeData.txt>")
    names = {}
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            fields = line.split(";")
            if len(fields) > 1:
                names[fields[1]] = int(fields[0], 16)
    table = {}
    for name, cp in names.items():
        m = re.fullmatch(r"BLOCK OCTANT-([1-8]+)", name)
        if m:
            table[bits(int(d) for d in m.group(1))] = cp
    for name, cells in OMITTED.items():
        if name == "SPACE":
            cp = 0x20
        elif name in names:
            cp = names[name]
        else:
            sys.exit(f"missing character: {name}")
        b = bits(cells)
        if b in table:
            sys.exit(f"pattern {b:#04x} mapped twice ({name})")
        table[b] = cp
    missing = [i for i in range(256) if i not in table]
    if missing:
        sys.exit(f"unmapped patterns: {missing}")
    out = [
        "// Generated by scripts/gen_octants.py from Unicode 16 UnicodeData.txt.",
        "// Do not edit by hand.",
        "",
        "#[rustfmt::skip]",
        "pub static OCTANT: [char; 256] = [",
    ]
    for r in range(0, 256, 8):
        row = ", ".join("'\\u{%X}'" % table[i] for i in range(r, r + 8))
        out.append(f"    {row},")
    out.append("];")
    print("\n".join(out))


main()
